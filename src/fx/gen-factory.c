/* gen-factory.c: writes factory.inc, the starter presets on the MPC's PRESETS page, from the shared
 * table src/chains/factory_presets.h. Each preset is a fresh insert plus the table's changes, written out
 * in full ("control index, value" per line, as a saved slot file) so loading one always lands on the
 * same sound. Fails on a name that matches no control or a value outside its range.
 *   cc -O2 -I. -DHS_MPC_LADSPA_RECALL gen-factory.c hs_ladspa.c hs_registry.c hs_eq2.c hs_pump.c hs_heat.c hs_distressor.c \
 *      hs_bass_focus.c hs_tube_strip.c hs_bus.c hs_xsat.c hs_channel.c hs_saturator.c hs_air_exciter.c hs_env.c \
 *      -lm -pthread -o /tmp/gen-factory && /tmp/gen-factory > factory.inc */
#include <ctype.h>
#include <math.h>
#include "../chains/factory_presets.h"
const LADSPA_Descriptor *ladspa_descriptor(unsigned long);

/* What the MPC host gives a fresh insert: the LADSPA hint default, whole-number controls rounded. */
static float fresh(const LADSPA_Descriptor *d, unsigned long p)
{
    const LADSPA_PortRangeHint *r = &d->PortRangeHints[p];
    LADSPA_PortRangeHintDescriptor h = r->HintDescriptor;
    double lo = r->LowerBound, hi = r->UpperBound, v = lo;
    int lg = LADSPA_IS_HINT_LOGARITHMIC(h) && lo > 0;
#define MIX(a) (lg ? exp(log(lo)*(1 - (a)) + log(hi)*(a)) : lo*(1 - (a)) + hi*(a))
    if (LADSPA_IS_HINT_DEFAULT_LOW(h)) v = MIX(.25); else if (LADSPA_IS_HINT_DEFAULT_MIDDLE(h)) v = MIX(.5);
    else if (LADSPA_IS_HINT_DEFAULT_HIGH(h)) v = MIX(.75); else if (LADSPA_IS_HINT_DEFAULT_MAXIMUM(h)) v = hi;
    else if (LADSPA_IS_HINT_DEFAULT_0(h)) v = 0;
    else if (LADSPA_IS_HINT_DEFAULT_1(h)) v = 1; else if (LADSPA_IS_HINT_DEFAULT_100(h)) v = 100;
    else if (LADSPA_IS_HINT_DEFAULT_440(h)) v = 440;
    /* ponytail: the host turns DEFAULT_1 on a stepped control into its maximum (seen on Heat and Bus
       Compressor, 12 Nov 2026); no effect with presets uses that combination any more, so it is not modelled. */
    return hs_snap_default(d, p, (float)v);
}

int main(void)
{
    puts("/* factory.inc: starter presets. GENERATED by gen-factory.c from ../chains/factory_presets.h: edit that, not this. */");
    puts("struct Factory { const char *label; int slot; const char *name; const char *text; };");
    puts("static const Factory factory[] = {");
    for (int i = 0; i < HS_FACTORY_PRESET_COUNT; ++i) {
        const hs_factory_preset *fp = &hs_factory_presets[i];
        const LADSPA_Descriptor *d = NULL;
        for (unsigned long k = 0; (d = ladspa_descriptor(k)) && strcmp(d->Label, fp->label); ++k) ;
        int slot = 0;
        for (int j = 0; j < i; ++j) slot += !strcmp(hs_factory_presets[j].label, fp->label);
        char err[160], name[15];
        float v[512];
        if (!d || d->PortCount > 512) { fprintf(stderr, "%s: no such effect\n", fp->label); return 1; }
        if (slot > 7 || strlen(fp->name) > 14) { fprintf(stderr, "%s %s: 8 slots, 14 characters\n", fp->label, fp->name); return 1; }
        for (unsigned long p = 0; p < d->PortCount; ++p) v[p] = hs_is_ctl_in(d, p) ? fresh(d, p) : 0;
        if (hs_preset_apply(d, fp->args, v, err, sizeof err)) { fprintf(stderr, "%s %s: %s\n", fp->label, fp->name, err); return 1; }
        for (size_t c = 0; c <= strlen(fp->name); ++c) name[c] = (char)toupper((unsigned char)fp->name[c]);   /* the panel font is capitals */
        printf("    {\"%s\", %d, \"%s\", \"", fp->label, slot, name);
        int n = 0;
        for (unsigned long p = 0; p < d->PortCount; ++p) if (hs_is_ctl_in(d, p)) printf("%d %.9g\\n", n++, v[p]);
        puts("\"},");
    }
    puts("};");
    return 0;
}
