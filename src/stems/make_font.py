#!/usr/bin/env python3
"""Writes font.h: ASCII 32-126 from DejaVu Sans Mono (free licence), 4-bit alpha, fixed cell.
usage: make_font.py DejaVuSansMono.ttf > font.h"""
import sys
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype(sys.argv[1], 13)
CW, CH, BASE = 8, 16, 12
print('// generated by make_font.py from DejaVu Sans Mono 13 px (Bitstream Vera licence)')
print(f'enum {{ FONT_W = {CW}, FONT_H = {CH} }};')
print('static const unsigned char FONT[95][FONT_H][FONT_W / 2] = {')
for c in range(32, 127):
    im = Image.new('L', (CW, CH), 0); ImageDraw.Draw(im).text((0, BASE), chr(c), font=f, fill=255, anchor='ls')
    rows = []
    for y in range(CH):
        px = [im.getpixel((x, y)) >> 4 for x in range(CW)]
        rows.append('{' + ','.join(str(px[x] << 4 | px[x + 1]) for x in range(0, CW, 2)) + '}')
    print('  {' + ','.join(rows) + '},')
print('};')
