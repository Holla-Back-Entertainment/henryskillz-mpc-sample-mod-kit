#!/usr/bin/env python3
"""Writes pad_glyphs.h: the Sample screen's pad-label glyphs, cut from lab shots in test/pad/.
usage: make_glyphs.py > pad_glyphs.h

test/pad/<layout>-<label>.png are 120x20 crops (screen y 50..69) of the Sample screen:
  mod-S03T01A06: "S03 T01 A06" (SampQOL adds sequence + track), 7 px cells at MOD_X
  stock-A06:     "A06" alone (stock app), 8 px cells at STOCK_X
Each glyph is the red channel (the label is orange on black). The script re-reads every crop the
way hs_stems_ui.c does (normalised correlation, fractional shift search) and fails on a miss."""
import glob, os, sys
import numpy as np
from PIL import Image

Y = 5            # glyph top inside the crop (screen y 55)
GH = 10
MOD_X = (12, 19, 26, 39, 46, 53, 65, 72, 79)
STOCK_X = (12, 20, 28)
SHIFTS = [d / 4 for d in range(-6, 7)]
here = os.path.dirname(os.path.abspath(__file__))

def red(path): return np.asarray(Image.open(path).convert('RGB')).astype(float)[:, :, 0]
def label(path): return os.path.basename(path)[:-4].split('-', 1)[1].rstrip('b')
def cut(a, x, w): return a[Y:Y + GH, x:x + w]

def build(layout, xs, w, slots):
    g = {}
    for p in sorted(glob.glob(f'{here}/test/pad/{layout}-*.png')):
        a, t = red(p), label(p)
        for i in slots:
            g.setdefault(t[i], []).append(cut(a, xs[i], w))
    return {c: np.mean(v, axis=0) for c, v in g.items()}

def norm(v):
    v = v - v.mean(); n = np.sqrt((v * v).sum()); return v / n if n else v

def read(a, xs, w, g):
    out, worst = '', 1.0
    for x in xs:
        best = (-2, '?')
        for dx in SHIFTS:
            i = int(np.floor(x + dx)); f = x + dx - i
            c = norm(cut(a, i, w) * (1 - f) + cut(a, i + 1, w) * f)
            for ch, t in g.items():
                best = max(best, ((c * norm(t)).sum(), ch))
        out += best[1]; worst = min(worst, best[0])
    return out, worst

# mod: digits and bank letters from the pad slot (6..8), S and T from their own slots
mod = build('mod', MOD_X, 7, (6, 7, 8))
mod.update({k: v for k, v in build('mod', MOD_X, 7, (0, 3)).items() if k in 'ST'})
stock = build('stock', STOCK_X, 8, (0, 1, 2))
for layout, xs, w, g in (('mod', MOD_X, 7, mod), ('stock', STOCK_X, 8, stock)):
    for p in sorted(glob.glob(f'{here}/test/pad/{layout}-*.png')):
        got, score = read(red(p), xs, w, g)
        assert got == label(p), (p, got)
        assert score > 0.9, (p, score)

def emit(name, g, w):
    chars = ''.join(sorted(g))
    print(f'static const char {name}_CH[] = "{chars}";')
    print(f'static const unsigned char {name}_G[{len(chars)}][{GH}][{w}] = {{')
    for c in chars:
        rows = ','.join('{' + ','.join(str(int(round(v))) for v in r) + '}' for r in g[c])
        print(f'  {{{rows}}},  /* {c} */')
    print('};')

print('// generated by make_glyphs.py from test/pad/*.png (lab shots of the Sample screen pad label)')
print(f'enum {{ GLYPH_H = {GH}, GLYPH_Y = 55 }};')
emit('MOD', mod, 7)
emit('STOCK', stock, 8)
