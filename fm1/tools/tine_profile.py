#!/usr/bin/env python3
"""Generate the integer pickup profile from measured harmonic magnitudes."""
import csv
import sys

# The recordings' SFZ maps suffix 5 to the lightest hits and 1 to the hardest.
VELOCITIES = {5: 35, 4: 60, 3: 84, 2: 104, 1: 122}

def gain(db):
    # A few bass recordings nearly cancel the fundamental at full strike.
    # Bound these ratios to retain headroom when playing dense chords.
    return round(4096 * min(2.8, 10 ** (float(db) / 20)))

def main():
    with open(sys.argv[1], newline="") as file:
        measurements = list(csv.DictReader(file))
    print("/* Generated by tools/tine_profile.py from jRhodes3d metrics.")
    print(" * Recordings by Jeffrey Learman. See research/README.md. */")
    print("static const PickupProfile profile[] = {")
    for row in measurements:
        attack = [gain(row[f"attack_h{h}_db_rel"]) for h in range(2, 6)]
        held = [gain(row[f"held_h{h}_db_rel"]) for h in range(2, 6)]
        # Some fundamentals grow after the strike. Use a modest positive decay
        # in this model, which has a passive envelope and separate partials.
        decay = round(max(.65, -float(row["held_f0_db_per_second"])) * 2.737)
        print(f'    {{{row["midi_note"]}, {VELOCITIES[int(row["layer"])]}, {decay}, '
              f'{{{", ".join(map(str, attack))}}}, {{{", ".join(map(str, held))}}}}},')
    print("};")

if __name__ == "__main__":
    main()
